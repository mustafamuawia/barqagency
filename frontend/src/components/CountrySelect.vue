const props = defineProps({
  modelValue: { type: String, default: '' },
  placeholder: { type: String, default: 'Search country...' },
  required: { type: Boolean, default: false },
  inputClass: { type: String, default: 'w-full border border-slate-200 rounded-lg px-2 py-1.5 text-xs focus:outline-none focus:ring-2 focus:ring-amber-400' },
})
const emit = defineEmits(['update:modelValue'])

const rootEl = ref(null)
const open = ref(false)
const highlighted = ref(0)
const selected = computed(() => COUNTRIES.find(c => c.code === props.modelValue))
const query = ref(selected.value ? `${selected.value.name} (${selected.value.code})` : '')

watch(() => props.modelValue, (code) => {
  const country = COUNTRIES.find(c => c.code === code)
  query.value = country ? `${country.name} (${country.code})` : ''
})

const results = computed(() => {
  const term = query.value.trim().toLowerCase()
  if (!term) return COUNTRIES.slice(0, 10)
  return COUNTRIES
    .filter(c =>
      c.code.toLowerCase().startsWith(term) ||
      c.name.toLowerCase().includes(term)
    )
    .slice(0, 10)
})

const move = (delta) => {
  if (!results.value.length) return
  highlighted.value = (highlighted.value + delta + results.value.length) % results.value.length
}

const select = (country) => {
  query.value = `${country.name} (${country.code})`
  open.value = false
  emit('update:modelValue', country.code)
}

const selectHighlighted = () => {
  if (open.value && results.value[highlighted.value]) select(results.value[highlighted.value])
}

const onClickOutside = (event) => {
  if (rootEl.value && !rootEl.value.contains(event.target)) {
    open.value = false
    if (!selected.value || query.value !== `${selected.value.name} (${selected.value.code})`) {
      query.value = selected.value ? `${selected.value.name} (${selected.value.code})` : ''
    }
  }
}
onMounted(() => document.addEventListener('click', onClickOutside))
onBeforeUnmount(() => document.removeEventListener('click', onClickOutside))
